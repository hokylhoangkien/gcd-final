"""Check source/config drift in the reviewed manuscript and its rendered PDF.

--write regenerates only the marked settings table after a semantic review.
The digest detects changed implementation inputs; it cannot verify prose.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gcd_runtime.config import load_config

PAPER = ROOT/'paper/manuscript.tex'
BEGIN = '% BEGIN IMPLEMENTATION_SETTINGS'
END = '% END IMPLEMENTATION_SETTINGS'


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def implementation_digest():
    paths = [p for folder in ('crish', 'gcd_runtime', 'audit')
             for p in (ROOT/folder).glob('*.py')]
    paths.extend(p for p in (ROOT/'configs').glob('*.json')
                 if json.loads(p.read_text()).get('method') in ('baseline', 'crish'))
    for pattern in ('*.py', '*.cmd', '*.pkl'):
        paths.extend((ROOT/'upstream/HypCD').rglob(pattern))
    paths.append(Path(__file__))
    hashes = {str(p.relative_to(ROOT)): sha256(p) for p in sorted(set(paths))}
    return hashlib.sha256(json.dumps(hashes, sort_keys=True).encode()).hexdigest()


def settings_block():
    names = ('crish', 'crish_upgraded', 'cub_crish', 'cub_crish_upgraded')
    profiles = [load_config(ROOT/'configs'/f'{name}.json') for name in names]
    for name, config in zip(names, profiles):
        control = load_config(ROOT/'configs'/f'{name.replace("crish", "baseline")}.json')
        if {key for key in config.keys() | control.keys()
                if config.get(key) != control.get(key)} != {'method'}:
            raise ValueError(f'B0/CRiSH settings are no longer matched: {name}')

    def value(c, key):
        v = c['crish'][key] if key in c['crish'] else c[key]
        aliases = {'best_old_test_v2': 'Old-test-v2', 'final_epoch': 'last',
                   'global_neighbors': 'global shortlist', 'class_balanced': 'class balanced'}
        return aliases.get(v, f'{v:g}' if isinstance(v, (float, int)) else str(v)).replace('_', r'\_')

    rows = [
        ('Epochs / batch', lambda c: value(c, 'epochs')+' / '+value(c, 'batch_size')),
        ('SGD learning rate / momentum', lambda c: value(c, 'lr')+' / '+value(c, 'momentum')),
        ('Weight decay', lambda c: value(c, 'weight_decay')),
        ('Trainable blocks start at', lambda c: value(c, 'grad_from_block')),
        ('USE normalization', lambda c: value(c, 'use_target_normalization')),
        ('USE smoothing $\\alpha$', lambda c: value(c, 'unsupervised_smoothing')),
        ('Hyperbolic maximum weight', lambda c: value(c, 'hyper_max_weight')),
        ('Curvature / clipping radius', lambda c: value(c, 'c')+' / '+value(c, 'cr')),
        ('Repair warmup / interval', lambda c: value(c, 'warmup_epochs')+' / '+value(c, 'refresh_every')),
        ('Evidence cache / trials / $k$', lambda c: ' / '.join(value(c,k) for k in ('evidence_samples','evidence_trials','k'))),
        ('Evidence sampling', lambda c: value(c, 'evidence_sampling')),
        ('Proposal scoring batch', lambda c: value(c, 'train_batch')),
        ('Known / unlabeled per probe fold', lambda c: value(c, 'probe_known')+' / '+value(c, 'probe_unlabeled')),
        ('Known probe sampling', lambda c: value(c, 'probe_sampling')),
        ('M2 trials (zero means disabled)', lambda c: value(c, 'stability_trials')),
        ('Boundaries / destinations / accepted', lambda c: ' / '.join(value(c,k) for k in ('boundaries','max_targets','max_accepted'))),
        ('Minimum support / edges', lambda c: value(c, 'min_support')+' / '+value(c, 'min_edges')),
        ('Minimum joint reliability', lambda c: value(c, 'min_reliability')),
        ('Gain threshold / known tolerance', lambda c: value(c, 'acceptance_gain')+' / '+value(c, 'known_tolerance')),
        ('Protected coefficient shift cap', lambda c: value(c, 'max_protected_shift')),
        ('Refresh budget (seconds)', lambda c: value(c, 'max_refresh_seconds')),
        ('Probe weights: known / view / variance', lambda c: ' / '.join(value(c,k) for k in ('probe_known_weight','probe_view_weight','probe_variance_weight'))),
        ('Probe standard-deviation floor', lambda c: value(c, 'probe_std_floor')),
        ('Checkpoint selection', lambda c: value(c, 'checkpoint_selection')),
    ]
    lines = [BEGIN, '% Generated by scripts/check_manuscript.py --write.',
             '% implementation-sha256: '+implementation_digest(),
             r'\begin{table*}[!t]\footnotesize\centering',
             r'\caption{Actual full-profile settings, generated from source configs. All four profiles use projector-only lookahead and normalized-backbone Euclidean evidence.}',
             r'\begin{tabularx}{\textwidth}{@{}Xcccc@{}}\toprule',
             r'Setting & Cars ref. & Cars upgraded & CUB ref. & CUB upgraded\\\midrule']
    lines.extend(label+' & '+' & '.join(fn(c) for c in profiles)+r'\\' for label,fn in rows)
    lines.extend([r'\bottomrule\end{tabularx}\label{tab:settings}', r'\end{table*}', END])
    return '\n'.join(lines)


def check_source():
    text = PAPER.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError('Manuscript needs exactly one settings block')
    actual = text[text.index(BEGIN):text.index(END)+len(END)]
    if actual != settings_block():
        raise ValueError('Manuscript source/config contract changed: review equations/policy, then run --write')
    citations = {key.strip() for group in re.findall(r'\\cite\{([^}]+)\}', text) for key in group.split(',')}
    bibliography = re.findall(r'\\bibitem\{([^}]+)\}', text)
    if citations-set(bibliography) or len(bibliography) != len(set(bibliography)):
        raise ValueError('Missing or duplicate manuscript bibliography keys')
    labels = re.findall(r'\\label\{([^}]+)\}', text)
    references = set(re.findall(r'\\(?:ref|eqref)\{([^}]+)\}', text))
    if references-set(labels) or len(labels) != len(set(labels)):
        raise ValueError('Missing or duplicate manuscript equation/table references')
    return implementation_digest()


def check_pdf(digest):
    receipt = json.loads((ROOT/'paper/manuscript.build.json').read_text())
    expected = dict(tex_sha256=sha256(PAPER), pdf_sha256=sha256(ROOT/'paper/manuscript.pdf'),
                    implementation_sha256=digest)
    if any(receipt.get(key) != v for key,v in expected.items()):
        raise ValueError('PDF/source receipt is stale: rebuild with scripts/build_paper.py')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Regenerate the table/digest after semantic review')
    parser.add_argument('--source-only', action='store_true', help='Skip PDF provenance while preparing a new build')
    args = parser.parse_args()
    if args.write:
        text = PAPER.read_text()
        if text.count(BEGIN) != 1 or text.count(END) != 1:
            raise ValueError('Missing/duplicate implementation settings markers')
        text = text[:text.index(BEGIN)]+settings_block()+text[text.index(END)+len(END):]
        PAPER.write_text(text)
    digest = check_source()
    if not args.write and not args.source_only:
        check_pdf(digest)
    print(json.dumps(dict(status='passed', implementation_sha256=digest,
                          check='source_table_and_digest' if args.write or args.source_only else 'source_table_digest_and_pdf_receipt')))
